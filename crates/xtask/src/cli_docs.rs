//! xtask cli-docs: generated CLI reference for the testability bins
//! (robustness-ci leaf 05.04).
//!
//! Shells out to each built bin's `--help` and `--version` (clap-derive owns
//! the real text; zero refactor of the bins) and renders
//! `docs/testability-clis.md`. `--check` regenerates in memory and diffs the
//! committed file - same drift-gate pattern as `notices`.
//!
//! A bin missing from target/debug is tolerated with a noted line (leaf
//! 05.02's ap-parse-check may still be landing when this runs).

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub const DOCS_PATH: &str = "docs/testability-clis.md";

/// (bin name, owning crate, crate dir relative to workspace root) in
/// deterministic render order.
pub const CLIS: [(&str, &str); 6] = [
    ("ap-run-eval", "ap-cli"),
    ("ap-obj-eval", "ap-cli"),
    ("ap-ir-dump", "ap-parse"),
    ("ap-verify-dump", "ap-parse"),
    ("ap-parse-check", "ap-parse"),
    ("ap-conform", "ap-conform"),
];

const HEADER: &str = "\
# Testability CLIs

Generated CLI reference for the repo's testability bins. The help text below
is the bins' real clap-derive output at the committed revision - it is the
contract the pytest suites pin, mirrored for humans.

Generated by `cargo run -p xtask -- cli-docs` (runs each built bin's
`--help`/`--version` from `target/debug`; build with
`cargo build -p ap-cli -p ap-parse -p ap-conform --bins` first).
Do not edit by hand; regenerate instead.
CI gate: `cargo run -p xtask -- cli-docs --check` fails if this file is stale.

";

fn debug_dir(root: &Path) -> PathBuf {
    // Under `cargo run -p xtask`, cargo sets CARGO_TARGET_DIR to the real
    // target dir (may differ from root/target with sccache/custom configs).
    match std::env::var("CARGO_TARGET_DIR") {
        Ok(d) if !d.is_empty() => PathBuf::from(d).join("debug"),
        _ => root.join("target").join("debug"),
    }
}

/// Run one bin with `arg`, returning stdout on success. None = bin missing
/// or non-zero exit (a `--help`/`--version` invocation of a clap bin is
/// exit-0 by contract; anything else is treated as "not documentable").
fn capture_help(bin: &Path, arg: &str) -> Option<String> {
    let out = Command::new(bin).arg(arg).output().ok()?;
    if !out.status.success() {
        return None;
    }
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    // clap prints a single trailing newline; normalize CRLF just in case.
    text = text.replace("\r\n", "\n");
    if !text.ends_with('\n') {
        text.push('\n');
    }
    Some(text)
}

/// Pure renderer: one section per CLI. `help`/`version` are Option so the
/// missing-bin case is unit-testable without touching target/debug.
pub fn render_sections(sections: &[(&str, &str, Option<String>, Option<String>)]) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    for (name, krate, help, version) in sections {
        let _ = writeln!(out, "## `{name}` (crate `{krate}`)");
        let _ = writeln!(out);
        let _ = writeln!(out, "Binary path: `target/debug/{name}`");
        let _ = writeln!(out);
        match help {
            Some(h) => {
                let _ = writeln!(out, "Version (`{name} --version`):");
                let _ = writeln!(out);
                let _ = writeln!(out, "```text");
                out.push_str(version.as_deref().unwrap_or("(--version failed)\n"));
                let _ = writeln!(out, "```");
                let _ = writeln!(out);
                let _ = writeln!(out, "Help (`{name} --help`):");
                let _ = writeln!(out);
                let _ = writeln!(out, "```text");
                out.push_str(h);
                let _ = writeln!(out, "```");
            }
            None => {
                let _ = writeln!(
                    out,
                    "NOT BUILT at generation time: run `cargo build -p {krate} --bins` \
                     and regenerate. This section is a placeholder; the CI drift gate \
                     regenerates against the current tree."
                );
            }
        }
        let _ = writeln!(out);
    }
    out
}

/// Collect the live help/version text for every registered CLI.
pub fn collect(root: &Path) -> Vec<(&'static str, &'static str, Option<String>, Option<String>)> {
    let dir = debug_dir(root);
    CLIS.iter()
        .map(|(name, krate)| {
            let bin = dir.join(name);
            if bin.is_file() {
                (
                    *name,
                    *krate,
                    capture_help(&bin, "--help"),
                    capture_help(&bin, "--version"),
                )
            } else {
                (*name, *krate, None, None)
            }
        })
        .collect()
}

pub fn render(root: &Path) -> String {
    render_sections(&collect(root))
}

/// Entry point for `cargo run -p xtask -- cli-docs [--check]`.
pub fn run(check: bool) -> ! {
    let root = crate::workspace_root();
    let rendered = render(&root);
    let path = root.join(DOCS_PATH);

    if check {
        let committed = fs::read_to_string(&path).unwrap_or_else(|e| {
            eprintln!(
                "cli-docs --check: {}: {e}\nRun `cargo run -p xtask -- cli-docs` to generate it.",
                path.display()
            );
            std::process::exit(2);
        });
        if committed != rendered {
            eprintln!(
                "CLI-DOCS DRIFT: {DOCS_PATH} is stale relative to the built bins' --help output.\n\
                 Run `cargo build -p ap-cli -p ap-parse -p ap-conform --bins && \
                 cargo run -p xtask -- cli-docs` and commit the result."
            );
            std::process::exit(1);
        }
        println!("cli-docs --check: OK ({} CLIs documented)", CLIS.len());
        std::process::exit(0);
    }

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).unwrap_or_else(|e| {
            eprintln!("failed to create {}: {e}", parent.display());
            std::process::exit(2);
        });
    }
    fs::write(&path, &rendered).unwrap_or_else(|e| {
        eprintln!("failed to write {}: {e}", path.display());
        std::process::exit(2);
    });
    let documented = rendered.matches("## `").count();
    println!("wrote {} ({} CLI sections)", path.display(), documented);
    std::process::exit(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_sections_is_deterministic_and_structured() {
        let secs = [
            (
                "b-bin",
                "b-crate",
                Some("usage: b-bin\n".to_string()),
                Some("b-bin 0.1.0\n".to_string()),
            ),
            ("a-bin", "a-crate", None, None),
        ];
        let once = render_sections(&secs);
        let twice = render_sections(&secs);
        assert_eq!(once, twice, "render must be a pure function of sections");
        assert!(once.starts_with(HEADER));
        // Section order follows the slice (CLIS order), not the filesystem.
        let pa = once.find("## `a-bin`").expect("a-bin section rendered");
        let pb = once.find("## `b-bin`").expect("b-bin section rendered");
        assert!(pb < pa, "sections render in slice order");
        assert!(once.contains("usage: b-bin"));
        assert!(once.contains("b-bin 0.1.0"));
        assert!(once.contains("Binary path: `target/debug/b-bin`"));
        // Missing-bin tolerance (leaf 05.02 may not have landed yet).
        assert!(once.contains("NOT BUILT"));
        assert!(once.contains("cargo build -p a-crate --bins"));
    }

    #[test]
    fn registered_clis_match_review_roadmap_set() {
        let names: Vec<&str> = CLIS.iter().map(|(n, _)| *n).collect();
        for expected in [
            "ap-run-eval",
            "ap-obj-eval",
            "ap-ir-dump",
            "ap-verify-dump",
            "ap-parse-check",
            "ap-conform",
        ] {
            assert!(names.contains(&expected), "{expected} missing from CLIS");
        }
    }

    #[test]
    fn collect_returns_one_row_per_cli() {
        let rows = collect(&crate::workspace_root());
        assert_eq!(rows.len(), CLIS.len());
    }
}
