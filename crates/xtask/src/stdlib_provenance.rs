/// Compare the vendored tree against upstream + the declared manifest.
/// Returns `(problems, total_files, deviated_declared)`; empty problems == OK.
pub fn stdlib_provenance_check(
    vendored_root: &Path,
    upstream_root: &Path,
    manifest: &Manifest,
) -> (Vec<String>, usize, usize) {
    let mut problems = Vec::new();
    let walked = match walk_vendored(vendored_root) {
        Ok(w) => w,
        Err(e) => return (vec![e], 0, 0),
    };
    // Gate 5: the manifest must cover exactly the walked file set.
    for extra in manifest
        .files
        .keys()
        .filter(|k| !walked.iter().any(|w| w == *k))
    {
        problems.push(format!(
            "undeclared-file: manifest entry for {extra:?} but not on disk"
        ));
    }
    for missing in walked.iter().filter(|w| !manifest.files.contains_key(*w)) {
        problems.push(format!(
            "coverage: file {missing:?} has no DEVIATIONS.toml entry"
        ));
    }

    for rel in &walked {
        let local_path = vendored_root.join(rel);
        let local = match fs::read(&local_path) {
            Ok(b) => b,
            Err(e) => {
                problems.push(format!("unreadable {rel}: {e}"));
                continue;
            }
        };
        let local_sha = sha256_hex(&local);
        let entry = manifest.files.get(rel);
        let upstream_rel = entry
            .map(|e| e.upstream_path.as_str())
            .unwrap_or(rel.as_str());
        let upstream_sha = if upstream_rel.is_empty() {
            None
        } else {
            fs::read(upstream_root.join(upstream_rel))
                .ok()
                .map(|b| sha256_hex(&b))
        };

        match entry {
            None => {
                // Undeclared file: must match upstream bytes exactly.
                match &upstream_sha {
                    Some(us) if *us == local_sha => {}
                    Some(us) => problems.push(format!(
                        "UNDECLARED DRIFT: {rel} differs from upstream (local {local_sha}, upstream {us}) — declare it in DEVIATIONS.toml or restore the pristine bytes"
                    )),
                    None => problems.push(format!(
                        "UNDECLARED UNAVAILABLE: {rel} is undeclared and no upstream file exists at {upstream_rel}"
                    )),
                }
            }
            Some(e) => match e.status {
                Status::Pristine => {
                    if upstream_rel.is_empty() {
                        problems.push(format!(
                            "bad declaration: {rel} declared pristine with empty upstream_path"
                        ));
                    } else {
                        match &upstream_sha {
                            None => problems.push(format!(
                                "upstream missing: {rel} declared pristine but {upstream_rel:?} not found under {}",
                                upstream_root.display()
                            )),
                            Some(us) => {
                                if !e.upstream_sha256.is_empty() && *us != e.upstream_sha256 {
                                    problems.push(format!(
                                        "stale manifest: upstream bytes of {upstream_rel:?} differ from recorded upstream_sha256 (interpreter patch?)"
                                    ));
                                }
                                if *us != local_sha {
                                    problems.push(format!(
                                        "PRISTINE BROKEN: declared-pristine {rel} does not match upstream bytes"
                                    ));
                                }
                            }
                        }
                    }
                }
                Status::Deviated => {
                    let matches_declared =
                        !e.deviated_sha256.is_empty() && e.deviated_sha256 == local_sha;
                    let matches_upstream = upstream_sha.as_deref() == Some(local_sha.as_str());
                    if !matches_declared && !matches_upstream {
                        problems.push(format!(
                            "STALE DECLARATION: deviated {rel} matches neither upstream nor deviated_sha256 ({}) — re-declare via --fix review",
                            e.deviated_sha256
                        ));
                    }
                    if let Some(us) = &upstream_sha {
                        if !e.upstream_sha256.is_empty() && *us != e.upstream_sha256 {
                            problems.push(format!(
                                "stale manifest: upstream bytes of {upstream_rel:?} differ from recorded upstream_sha256 (interpreter patch?)"
                            ));
                        }
                    } else if !upstream_rel.is_empty() {
                        problems.push(format!(
                            "upstream missing: deviated {rel} names upstream {upstream_rel:?}, not found under {}",
                            upstream_root.display()
                        ));
                    }
                }
            },
        }
    }
    let deviated = manifest
        .files
        .values()
        .filter(|e| e.status == Status::Deviated)
        .count();
    problems.sort();
    (problems, walked.len(), deviated)
}

// ---------------------------------------------------------------------------
// --fix: regenerate pristine entries
// ---------------------------------------------------------------------------

/// Rewrite `manifest` with regenerated PRISTINE entries for every walked file
/// that matches upstream bytes; deviated entries pass through untouched;
/// files that match nothing (undeclared drift) are reported in `needs_decl`
/// and NOT auto-declared (a deviation is a human decision).
pub fn apply_fix(
    vendored_root: &Path,
    upstream_root: &Path,
    manifest: &Manifest,
) -> Result<(Manifest, Vec<String>), String> {
    let walked = walk_vendored(vendored_root)?;
    let mut out = Manifest::default();
    let mut needs_decl = Vec::new();
    for rel in walked {
        let local = fs::read(vendored_root.join(&rel)).map_err(|e| format!("read {rel}: {e}"))?;
        let local_sha = sha256_hex(&local);
        if let Some(existing) = manifest.files.get(&rel) {
            if existing.status == Status::Deviated {
                out.files.insert(rel.clone(), existing.clone());
                continue;
            }
        }
        // Default upstream identity = same relative path.
        let upstream_rel = rel.clone();
        match fs::read(upstream_root.join(&upstream_rel)) {
            Ok(bytes) => {
                let us = sha256_hex(&bytes);
                if us == local_sha {
                    out.files.insert(
                        rel.clone(),
                        FileEntry {
                            path: rel.clone(),
                            upstream_path: upstream_rel,
                            status: Status::Pristine,
                            upstream_sha256: us,
                            deviated_sha256: local_sha,
                            note: String::new(),
                        },
                    );
                } else {
                    needs_decl.push(rel);
                }
            }
            Err(_) => needs_decl.push(rel),
        }
    }
    Ok((out, needs_decl))
}

