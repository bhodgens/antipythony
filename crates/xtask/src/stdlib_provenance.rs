/// Relative (slash-separated) paths of all files under `root`, excluding
/// NOTICE.md / DEVIATIONS.toml at the tree root and any `__pycache__` dir.
/// Sorted, deterministic.
pub fn walk_vendored(root: &Path) -> Result<Vec<String>, String> {
    let mut out = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let rd = fs::read_dir(&dir).map_err(|e| format!("read_dir {}: {e}", dir.display()))?;
        for de in rd {
            let de = de.map_err(|e| format!("read_dir entry: {e}"))?;
            let name = de.file_name().to_string_lossy().to_string();
            let path = de.path();
            if path.is_dir() {
                if name == "__pycache__" {
                    continue;
                }
                stack.push(path);
                continue;
            }
            if path.is_file() {
                if dir == root && (name == "NOTICE.md" || name == MANIFEST_NAME) {
                    continue;
                }
                let rel = path
                    .strip_prefix(root)
                    .map_err(|e| format!("strip {}: {e}", path.display()))?
                    .to_string_lossy()
                    .replace('\\', "/");
                out.push(rel);
            }
        }
    }
    out.sort();
    Ok(out)
}

