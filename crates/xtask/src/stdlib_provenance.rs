fn probe_python_stdlib(exe: &str) -> Option<PathBuf> {
    let out = Command::new(exe)
        .args([
            "-c",
            "import sysconfig;print(sysconfig.get_paths()['stdlib'])",
        ])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let text = String::from_utf8_lossy(&out.stdout).trim().to_string();
    let p = PathBuf::from(&text);
    if p.join("enum.py").is_file() {
        Some(p)
    } else {
        None
    }
}

fn cellar_candidates() -> Vec<PathBuf> {
    // Homebrew Cellar layout per AGENTS.md; both prefixes on Apple Silicon
    // and Intel. Newest version dir wins if several are installed.
    let mut found = Vec::new();
    for prefix in ["/opt/homebrew", "/usr/local"] {
        let cellar = Path::new(prefix).join("Cellar").join("python@3.14");
        let Ok(rd) = fs::read_dir(&cellar) else {
            continue;
        };
        for de in rd.flatten() {
            let p = de
                .path()
                .join("Frameworks/Python.framework/Versions/3.14/lib/python3.14");
            if p.join("enum.py").is_file() {
                found.push(p);
            }
        }
    }
    found.sort();
    found
}

pub fn resolve_upstream_lib() -> Option<PathBuf> {
    if let Ok(v) = std::env::var(UPSTREAM_LIB_ENV) {
        let p = PathBuf::from(v);
        if p.join("enum.py").is_file() {
            return Some(p);
        }
        return None;
    }
    for exe in ["python3.14", "python3", "python"] {
        if let Some(p) = probe_python_stdlib(exe) {
            return Some(p);
        }
    }
    cellar_candidates().pop()
}

