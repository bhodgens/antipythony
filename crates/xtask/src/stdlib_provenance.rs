pub fn run(argv: &[String], root: &Path) -> ! {
    let check = argv.iter().any(|a| a == "--check");
    let fix = argv.iter().any(|a| a == "--fix");
    let vendored = root.join("vendored_stdlib");
    let manifest_path = vendored.join(MANIFEST_NAME);

    if !vendored.is_dir() {
        eprintln!(
            "stdlib-provenance: no vendored_stdlib/ under {}",
            root.display()
        );
        exit(2);
    }
    if check && fix {
        eprintln!("stdlib-provenance: --check and --fix are mutually exclusive");
        exit(2);
    }

    let upstream = match resolve_upstream_lib() {
        Some(p) => p,
        None => {
            eprintln!(
                "stdlib-provenance: cannot locate CPython 3.14 Lib/ — set {UPSTREAM_LIB_ENV} \
                 or put python3.14/python3 on PATH (AGENTS.md: Homebrew Cellar path)"
            );
            exit(2);
        }
    };

    // No flags => report == --check (read-only).
    let mode = if fix { "fix" } else { "check" };

    let existing = if manifest_path.is_file() {
        match fs::read_to_string(&manifest_path) {
            Ok(t) => Manifest::parse(&t),
            Err(e) => Err(vec![format!("read manifest: {e}")]),
        }
    } else if mode == "check" {
        Err(vec![format!(
            "missing manifest: {} — run `cargo run -p xtask -- stdlib-provenance --fix`",
            manifest_path.display()
        )])
    } else {
        Ok(Manifest::default())
    };
    let manifest = match existing {
        Ok(m) => m,
        Err(errors) => {
            for e in &errors {
                eprintln!("stdlib-provenance: {e}");
            }
            exit(2);
        }
    };

    if mode == "fix" {
        let (fixed, needs_decl) = match apply_fix(&vendored, &upstream, &manifest) {
            Ok(v) => v,
            Err(e) => {
                eprintln!("stdlib-provenance: {e}");
                exit(2);
            }
        };
        if let Err(e) = fs::write(&manifest_path, fixed.render()) {
            eprintln!("stdlib-provenance: write {}: {e}", manifest_path.display());
            exit(2);
        }
        println!(
            "stdlib-provenance: fixed {} — {} pristine, {} deviated preserved",
            manifest_path.display(),
            fixed.files.len()
                - fixed
                    .files
                    .values()
                    .filter(|e| e.status == Status::Deviated)
                    .count(),
            fixed
                .files
                .values()
                .filter(|e| e.status == Status::Deviated)
                .count()
        );
        if !needs_decl.is_empty() {
            println!(
                "stdlib-provenance: {} file(s) NOT regenerated (drift vs upstream, no declaration) — add [[file]] status=\"deviated\" entries with notes from LICENSES/README-vendored-stdlib.md: {}",
                needs_decl.len(),
                needs_decl.join(", ")
            );
            exit(1);
        }
        exit(0);
    }

    let (problems, total, deviated) = stdlib_provenance_check(&vendored, &upstream, &manifest);
    if !problems.is_empty() {
        for p in &problems {
            eprintln!("stdlib-provenance: {p}");
        }
        eprintln!(
            "stdlib-provenance: FAIL ({total} files, {deviated} deviated declared, {} problem(s))",
            problems.len()
        );
        exit(1);
    }
    println!("stdlib-provenance: OK ({total} files, {deviated} deviated declared)");
    exit(0)
}

