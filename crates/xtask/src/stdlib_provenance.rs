    fn sha256_fips_vectors() {
        assert_eq!(
            sha256_hex(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        // multi-block input (1000 x 'a'), canonical vector
        let big = vec![b'a'; 1000];
        assert_eq!(
            sha256_hex(&big),
            "41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3"
        );
        // length-padding boundary: 55 bytes fit, 56 spills into a second block
        assert_eq!(
            sha256_hex(&[b'a'; 55]),
            "9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318"
        );
        assert_eq!(
            sha256_hex(&[b'a'; 56]),
            "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a"
        );
        assert_eq!(
            sha256_hex(&[b'a'; 64]),
            "ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb"
        );
    }

    struct Fix {
        dir: PathBuf,
    }
    impl Fix {
        fn fixture(name: &str) -> Fix {
            let pid = std::process::id();
            let dir = std::env::temp_dir().join(format!(
                "xtask-stdlib-prov-{name}-{pid}-{}",
                std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .map(|d| d.as_nanos())
                    .unwrap_or(0)
            ));
            fs::create_dir_all(dir.join("vendored")).expect("fixture io");
            fs::create_dir_all(dir.join("upstream")).expect("fixture io");
            Fix { dir }
        }
        fn put_vendored(&self, rel: &str, bytes: &[u8]) {
            let p = self.dir.join("vendored").join(rel);
            fs::create_dir_all(p.parent().expect("fixture io")).expect("fixture io");
            fs::write(p, bytes).expect("fixture io");
        }
        fn put_upstream(&self, rel: &str, bytes: &[u8]) {
            let p = self.dir.join("upstream").join(rel);
            fs::create_dir_all(p.parent().expect("fixture io")).expect("fixture io");
            fs::write(p, bytes).expect("fixture io");
        }
    }
    impl Drop for Fix {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.dir);
        }
    }

    fn entry(
        path: &str,
        upstream: &str,
        status: Status,
        upstream_sha: &str,
        deviated_sha: &str,
        note: &str,
    ) -> FileEntry {
        FileEntry {
            path: path.to_string(),
            upstream_path: upstream.to_string(),
            status,
            upstream_sha256: upstream_sha.to_string(),
            deviated_sha256: deviated_sha.to_string(),
            note: note.to_string(),
        }
    }

    fn manifest_of(entries: Vec<FileEntry>) -> Manifest {
        Manifest {
            files: entries.into_iter().map(|e| (e.path.clone(), e)).collect(),
        }
    }

