#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
    Pristine,
    Deviated,
}

#[derive(Clone, Debug)]
pub struct FileEntry {
    pub path: String,
    pub upstream_path: String,
    pub status: Status,
    pub upstream_sha256: String,
    pub deviated_sha256: String,
    pub note: String,
}

/// Parsed DEVIATIONS.toml. BTreeMap keyed by path => deterministic iteration.
#[derive(Clone, Debug, Default)]
pub struct Manifest {
    pub files: BTreeMap<String, FileEntry>,
}

fn parse_status(v: &str) -> Option<Status> {
    match v {
        "pristine" => Some(Status::Pristine),
        "deviated" => Some(Status::Deviated),
        _ => None,
    }
}

fn unquote(raw: &str) -> Result<String, String> {
    let raw = raw.trim();
    let mut chars = raw.chars();
    if chars.next() != Some('"') {
        return Err(format!("value must be a quoted string: {raw}"));
    }
    let inner = chars.as_str();
    let Some(end) = inner.rfind('"') else {
        return Err(format!("unterminated string: {raw}"));
    };
    if &inner[end..] != "\"" {
        // trailing content after the closing quote (only whitespace allowed)
        if !inner[end + 1..].trim().is_empty() {
            return Err(format!("trailing content after string: {raw}"));
        }
    }
    let body = &inner[..end];
    let mut out = String::with_capacity(body.len());
    let mut escaped = body.chars();
    while let Some(c) = escaped.next() {
        if c == '\\' {
            match escaped.next() {
                Some('n') => out.push('\n'),
                Some('"') => out.push('"'),
                Some('\\') => out.push('\\'),
                Some(other) => return Err(format!("bad escape \\<{other}>")),
                None => return Err("trailing backslash".to_string()),
            }
        } else if c == '"' {
            return Err("unescaped quote inside string".to_string());
        } else {
            out.push(c);
        }
    }
    Ok(out)
}

impl Manifest {
    pub fn parse(text: &str) -> Result<Manifest, Vec<String>> {
        let mut files = BTreeMap::new();
        let mut errors = Vec::new();
        let mut cur: Option<FileEntry> = None;
        let mut lineno = 0;

        let mut flush = |cur: &mut Option<FileEntry>, errors: &mut Vec<String>| {
            if let Some(e) = cur.take() {
                if e.path.is_empty() {
                    errors.push("entry with no `path` key".to_string());
                } else if files.insert(e.path.clone(), e).is_some() {
                    errors.push("duplicate path".to_string());
                }
            }
        };

        for line in text.lines() {
            lineno += 1;
            let t = line.trim();
            if t.is_empty() || t.starts_with('#') {
                continue;
            }
            if t == "[[file]]" {
                flush(&mut cur, &mut errors);
                cur = Some(FileEntry {
                    path: String::new(),
                    upstream_path: String::new(),
                    status: Status::Pristine,
                    upstream_sha256: String::new(),
                    deviated_sha256: String::new(),
                    note: String::new(),
                });
                continue;
            }
            let Some((key, raw)) = t.split_once('=') else {
                errors.push(format!("line {lineno}: not a key = value pair: {t}"));
                continue;
            };
            let Some(entry) = cur.as_mut() else {
                errors.push(format!("line {lineno}: key outside [[file]] table: {t}"));
                continue;
            };
            let val = match unquote(raw) {
                Ok(v) => v,
                Err(e) => {
                    errors.push(format!("line {lineno}: {e}"));
                    continue;
                }
            };
            let slot = match key.trim() {
                "path" => Some(&mut entry.path),
                "upstream_path" => Some(&mut entry.upstream_path),
                "upstream_sha256" => Some(&mut entry.upstream_sha256),
                "deviated_sha256" => Some(&mut entry.deviated_sha256),
                "note" => Some(&mut entry.note),
                "status" => {
                    match parse_status(&val) {
                        Some(s) => entry.status = s,
                        None => errors.push(format!("line {lineno}: bad status {val:?}")),
                    }
                    None
                }
                other => {
                    errors.push(format!("line {lineno}: unknown key {other}"));
                    None
                }
            };
            if let Some(dest) = slot {
                *dest = val;
            }
        }
        flush(&mut cur, &mut errors);

        // Structural validation (status/sha/note consistency).
        for e in files.values() {
            match e.status {
                Status::Deviated => {
                    if e.deviated_sha256.is_empty() {
                        errors.push(format!("deviated entry {} lacks deviated_sha256", e.path));
                    }
                    if e.note.is_empty() {
                        errors.push(format!("deviated entry {} lacks note", e.path));
                    }
                }
                Status::Pristine => {
                    if e.upstream_sha256.is_empty() || e.upstream_path.is_empty() {
                        errors.push(format!("pristine entry {} lacks upstream info", e.path));
                    }
                }
            }
        }
        if errors.is_empty() {
            Ok(Manifest { files })
        } else {
            Err(errors)
        }
    }

    pub fn render(&self) -> String {
        let mut out = String::from(MANIFEST_HEADER);
        for e in self.files.values() {
            out.push_str("\n[[file]]\n");
            let _ = writeln!(out, "path = \"{}\"", escape_val(&e.path));
            let _ = writeln!(out, "upstream_path = \"{}\"", escape_val(&e.upstream_path));
            let status = match e.status {
                Status::Pristine => "pristine",
                Status::Deviated => "deviated",
            };
            let _ = writeln!(out, "status = \"{status}\"");
            let _ = writeln!(
                out,
                "upstream_sha256 = \"{}\"",
                escape_val(&e.upstream_sha256)
            );
            let _ = writeln!(
                out,
                "deviated_sha256 = \"{}\"",
                escape_val(&e.deviated_sha256)
            );
            let _ = writeln!(out, "note = \"{}\"", escape_val(&e.note));
        }
        out
    }
}

fn escape_val(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            other => out.push(other),
        }
    }
    out
}

