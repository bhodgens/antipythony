//! xtask: repo maintenance tasks.
//!
//! `cargo run -p xtask -- notices`         regenerate THIRD_PARTY_NOTICES
//! `cargo run -p xtask -- notices --check` CI gate: fail on drift

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::exit;

use cargo_metadata::{MetadataCommand, Package};

mod license_fallbacks;

const NOTICES_PATH: &str = "THIRD_PARTY_NOTICES";
const HEADER: &str = "\
THIRD_PARTY_NOTICES for antipythany
===================================

This workspace is licensed Apache-2.0 WITH LLVM-exception (see LICENSE).
This file lists the third-party Cargo dependencies of the workspace, with
their licenses and copyright claims, as recorded by their manifests, plus
static entries for vendored source trees (not cargo crates; see
LICENSES/README-vendored-stdlib.md).

Generated by `cargo run -p xtask -- notices`. Deterministic output: entries
are sorted by (crate name, version). Do not edit by hand; regenerate instead.
CI gate: `cargo run -p xtask -- notices --check` fails if this file is stale.

";

struct Entry {
    name: String,
    version: String,
    license: String,
    copyright: String,
    license_text: String,
}

fn workspace_root() -> PathBuf {
    let manifest = std::env::var("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from("."));
    manifest
        .ancestors()
        .find(|p| p.join("Cargo.toml").exists() && p.join("crates").exists())
        .map(Path::to_path_buf)
        .expect("cannot locate workspace root")
}

/// Collect dependency crates: everything in the resolved workspace graph that
/// is not a workspace member itself.
fn collect_deps() -> Vec<Entry> {
    let md = MetadataCommand::new()
        .no_deps()
        .exec()
        .expect("cargo metadata failed");
    let root = md.workspace_root.clone();
    let members: Vec<&str> = md
        .workspace_members
        .iter()
        .map(|id| id.repr.as_str())
        .collect();

    let md = MetadataCommand::new()
        .current_dir(root)
        .exec()
        .expect("cargo metadata (with deps) failed");

    // Accumulate all (name, version) pairs actually resolved for workspace
    // dependency graphs (any platform/feature), so the gate is conservative.
    let mut used: BTreeMap<(String, String), Vec<&Package>> = BTreeMap::new();
    for resolve in md.resolve.iter() {
        for node in &resolve.nodes {
            let id = node.id.repr.as_str();
            if members.contains(&id) {
                continue;
            }
            let pkg = md
                .packages
                .iter()
                .find(|p| p.id.repr.as_str() == id)
                .expect("resolve node missing from packages");
            used.entry((pkg.name.to_string(), pkg.version.to_string()))
                .or_default()
                .push(pkg);
        }
    }

    let mut entries = Vec::new();
    for ((name, version), pkgs) in used {
        // Prefer the package whose manifest is on disk for license text.
        let pkg = pkgs
            .iter()
            .find(|p| p.manifest_path.exists())
            .copied()
            .unwrap_or(pkgs[0]);
        let license = pkg
            .license
            .clone()
            .unwrap_or_else(|| "UNKNOWN (no license field in manifest)".to_string());
        let copyright = copyright_of(pkg);
        let license_text = license_text_of(pkg, &license);
        entries.push(Entry {
            name,
            version,
            license,
            copyright,
            license_text,
        });
    }
    entries
}

/// Static entries for vendored source trees that are not cargo crates
/// (LICENSES/README-vendored-stdlib.md promised this: "the xtask generator
/// must be extended with a static-notices list"). Included only when the
/// vendored tree exists, so the notices file never claims files that are
/// not in the tree.
fn static_entries(root: &Path) -> Vec<Entry> {
    let mut out = Vec::new();
    if root.join("vendored_stdlib").is_dir() {
        let text = fs::read_to_string(root.join("LICENSES").join("PSF-LICENSE-2.0.txt"))
            .unwrap_or_else(|_| {
                "License text: LICENSES/PSF-LICENSE-2.0.txt (PSF License Version 2)".to_string()
            });
        out.push(Entry {
            name: "CPython vendored stdlib".to_string(),
            version: "3.14".to_string(),
            license: "PSF-2.0".to_string(),
            copyright: "Python Software Foundation".to_string(),
            license_text: text.trim_end().to_string(),
        });
    }
    out
}

/// Derive a copyright line: from the `authors` field if present, else the
/// repository owner, else "The <crate> Authors".
fn copyright_of(pkg: &Package) -> String {
    if !pkg.authors.is_empty() {
        return pkg.authors.join(", ");
    }
    if let Some(repo) = &pkg.repository {
        if let Some(owner) = repo
            .trim_start_matches("https://github.com/")
            .trim_start_matches("http://github.com/")
            .split('/')
            .next()
        {
            if !owner.is_empty() && owner != repo {
                return format!("The {} crate authors ({})", pkg.name, owner);
            }
        }
    }
    format!("The {} crate authors", pkg.name)
}

/// Best-effort license text: from a LICENSE* file next to the manifest, else a
/// vetted fallback text (see license_fallbacks), else a pointer to the crate's
/// source.
fn license_text_of(pkg: &Package, license: &str) -> String {
    let dir = pkg.manifest_path.parent().expect("manifest has parent");
    for name in [
        "LICENSE",
        "LICENSE.md",
        "LICENSE.txt",
        "LICENSE-APACHE",
        "LICENSE-MIT",
        "LICENSE-APACHE.md",
        "LICENSE-MIT.md",
        "LICENSE-ZLIB.md",
        "LICENSE-BSD",
        "LICENSE-ISC",
        "COPYING",
    ] {
        let p = dir.join(name);
        if let Ok(text) = fs::read_to_string(&p) {
            return text.trim_end().to_string();
        }
    }
    // LICENSE-MIT/LICENSE-APACHE style dual-license dirs.
    if license.contains("Apache") {
        if let Ok(t) = fs::read_to_string(dir.join("LICENSE-APACHE")) {
            return t.trim_end().to_string();
        }
    }
    if license.contains("MIT") {
        if let Ok(t) = fs::read_to_string(dir.join("LICENSE-MIT")) {
            return t.trim_end().to_string();
        }
    }
    if let Some(text) = license_fallbacks::fallbacks().get(&(pkg.name.as_str(), license)) {
        return (*text).to_string();
    }
    format!(
        "License text not shipped in the crate archive. Full text: {}\nLicense identifier(s): {}",
        pkg.id.repr.as_str(),
        license
    )
}

fn render(entries: &[Entry]) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    for e in entries {
        let _ = writeln!(
            out,
            "========================================================================="
        );
        let _ = writeln!(out, "{} v{}", e.name, e.version);
        let _ = writeln!(
            out,
            "-------------------------------------------------------------------------"
        );
        let _ = writeln!(out, "License: {}", e.license);
        let _ = writeln!(out, "Copyright: {}", e.copyright);
        let _ = writeln!(out);
        out.push_str(&e.license_text);
        let _ = writeln!(out);
        let _ = writeln!(out);
    }
    out
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let check = args.iter().any(|a| a == "--check");
    let root = workspace_root();
    let notices = root.join(NOTICES_PATH);

    let mut entries = collect_deps();
    entries.extend(static_entries(&root));
    let rendered = render(&entries);

    if check {
        let committed = fs::read_to_string(&notices).unwrap_or_else(|e| {
            eprintln!(
                "notices --check: {}: {e}\nRun `cargo run -p xtask -- notices` to generate it.",
                notices.display()
            );
            exit(2);
        });
        if committed != rendered {
            eprintln!(
                "NOTICES DRIFT: {NOTICES_PATH} is stale relative to Cargo.lock.\n\
                 Run `cargo run -p xtask -- notices` and commit the result."
            );
            exit(1);
        }
        println!(
            "notices --check: OK ({} third-party dependencies, up to date)",
            entries.len()
        );
        return;
    }

    fs::write(&notices, &rendered).unwrap_or_else(|e| {
        eprintln!("failed to write {}: {e}", notices.display());
        exit(2);
    });
    println!(
        "wrote {} ({} third-party dependencies)",
        notices.display(),
        entries.len()
    );
}
