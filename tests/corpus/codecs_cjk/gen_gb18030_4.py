#!/usr/bin/env python3
"""Generate the gb18030 four-byte encode/decode runs from the CPython 3.14
reference interpreter (byte-exactness contract: data FROM the ground-truth
interpreter). Writes crates/ap-run/src/mbc_gb18030_4.rs.

BMP: enumerated cp-by-cp; consecutive-cp runs (odometric +1 sequence advance)
become Gb4Run rows. Astral: pure odometric walk anchored at 0x10000 (the
BMP->astral sequence jump is NOT odometric, verified empirically).
"""
import json
import subprocess
import sys

REF = "/opt/homebrew/bin/python3.14"

src = r"""
import json
out = {}
for cp in range(0x80, 0x10000):
    if 0xD800 <= cp <= 0xDFFF: continue
    try:
        bs = chr(cp).encode('gb18030')
    except Exception:
        continue
    if len(bs) == 4:
        out[cp] = bs.hex()
print(json.dumps(out))
"""
proc = subprocess.run([REF, "-S", "-c", src], capture_output=True, text=True, timeout=300)
if proc.returncode != 0:
    print(proc.stderr[:500], file=sys.stderr)
    sys.exit(1)
d = {int(k): v for k, v in json.loads(proc.stdout).items()}
items = sorted(d.items())
runs = []
start = 0
for i in range(1, len(items) + 1):
    if i == len(items) or items[i][0] != items[i - 1][0] + 1:
        runs.append((items[start][0], items[start][1], items[i - 1][0]))
        start = i

def fmt(hexs):
    hb = bytes.fromhex(hexs)
    return "[" + ", ".join("0x%02X" % x for x in hb) + "]"

out = []
out.append("// @generated by tests/corpus/codecs_cjk/gen_gb18030_4.py — gb18030 four-byte")
out.append("// runs from CPython 3.14 (byte-exact). BMP part: runs of consecutive")
out.append("// codepoints whose sequences advance odometrically (+1 digit step per cp;")
out.append("// digit bytes 0x30-0x39 at positions 1/3, wide bytes 0x81-0xFE at 0/2).")
out.append("// Astral part: single odometric walk anchored at ASTRAL_ANCHOR (the")
out.append("// BMP->astral sequence jump at 0xffe6->0x10000 is NOT odometric).")
out.append("pub struct Gb4Run {")
out.append("    pub cp_start: u32,")
out.append("    pub cp_end: u32,")
out.append("    pub seq_start: [u8; 4],")
out.append("}")
out.append("")
out.append("pub static GB18030_4_BMP_RUNS: &[Gb4Run] = &[")
for cp_s, seq_s, cp_e in runs:
    out.append("    Gb4Run { cp_start: 0x%04X, cp_end: 0x%04X, seq_start: %s }," % (cp_s, cp_e, fmt(seq_s)))
out.append("];")
out.append("")
out.append("/// (cp, odometric-linear sequence index) anchor for the astral plane.")
out.append("pub const ASTRAL_ANCHOR_CP: u32 = 0x1_0000;")
out.append("pub const ASTRAL_ANCHOR_SEQ: [u8; 4] = " + fmt("90308130") + ";")
with open("crates/ap-run/src/mbc_gb18030_4.rs", "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote crates/ap-run/src/mbc_gb18030_4.rs (%d runs)" % len(runs))
