#!/usr/bin/env python3
"""Emit the gb18030 four-byte LINEAR ranges + boundary constants from CPython.

For each contiguous [start, end] cp range whose gb18030 encoding is exactly
4 bytes, the byte encoding is linear in cp: bytes = f(cp) with digit
advancement. We record (start_cp, start_bytes_hex, end_cp, end_bytes_hex);
the Rust engine linearly interpolates (per-digit increment).
"""
import subprocess
import json
import sys

REF = "/opt/homebrew/bin/python3.14"

src = r'''
import json
key = 'gb18030'
blocks = []
cur = None
for cp in range(0x80, 0x110000):
    ch = chr(cp)
    try:
        b = ch.encode(key)
        n = len(b)
    except Exception:
        n = None
    if cur is None or cur[1] != n:
        if cur is not None:
            blocks.append([cur[0], cur[1], cp - 1])
        cur = [cp, n]
    else:
        cur[1] = n
if cur is not None:
    blocks.append([cur[0], cur[1], 0x10ffff])
out = []
for b in blocks:
    if b[1] == 4:
        first = chr(b[0]).encode(key).hex()
        last = chr(b[2]).encode(key).hex()
        out.append([b[0], first, b[2], last])
print(json.dumps(out))
'''
proc = subprocess.run([REF, "-S", "-c", src], capture_output=True, text=True, timeout=900)
if proc.returncode != 0:
    print(proc.stderr[:500], file=sys.stderr)
    sys.exit(1)
ranges = json.loads(proc.stdout.strip().splitlines()[-1])
with open("crates/ap-run/src/mbc_gb18030_4.rs", "w") as f:
    f.write("// @generated by gen_gb18030_ranges.py — CPython 3.14 gb18030 four-byte linear\n")
    f.write("// ranges: (start_cp, start_bytes, end_cp, end_bytes). Encode: linear digit\n")
    f.write("// interpolation within a range; decode: the inverse (cp = start + digit delta).\n")
    f.write("pub static GB18030_4_LINEAR: &[(u32, [u8; 4], u32, [u8; 4])] = &[\n")
    for start, first, end, last in ranges:
        fb = bytes.fromhex(first)
        lb = bytes.fromhex(last)
        f.write(
            "    (0x%04X, [0x%02X, 0x%02X, 0x%02X, 0x%02X], 0x%04X, [0x%02X, 0x%02X, 0x%02X, 0x%02X]),\n"
            % (start, fb[0], fb[1], fb[2], fb[3], end, lb[0], lb[1], lb[2], lb[3])
        )
    f.write("];\n")
print("ranges:", len(ranges))
