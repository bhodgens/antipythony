#!/usr/bin/env python3
"""Generate docs/primitive-perf-chart.svg from bench_report.json.

Chart numbers are computed from the JSON, never hand-transcribed:
horizontal bars per primitive row, three bars per group
(CPython GB/s, antipythony GB/s, target GB/s) on a log-scale length
mapping (the measured spread is ~0.001 .. 483 GB/s). ERROR rows (no
antipythony measurement) render a hatched ERROR placeholder bar.
"""
import argparse
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOC = HERE / "../../../docs"

BAR_H = 16        # bar height px
BAR_GAP = 4       # gap between the three bars of a group
GROUP_GAP = 22    # gap between primitive groups
LABEL_W = 470     # left label column width
CHART_W = 520     # bar area width
BAR_X = LABEL_W + 10
GBS_MIN = 0.001   # log-scale floor
GBS_MAX = None    # computed from data
CPY_COLOR = "#4477aa"
APY_COLOR = "#ee7733"
TGT_COLOR = "#bbbbbb"
ERR_COLOR = "#cc3311"


def bar_len(gbs, gmax):
    """Log-scale length in px; floor at GBS_MIN."""
    lo, hi = math.log10(GBS_MIN), math.log10(gmax)
    v = max(math.log10(max(gbs, GBS_MIN)), lo)
    return (v - lo) / (hi - lo) * CHART_W


def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;")
             .replace(">", "&gt;"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default=str(HERE / "bench_report.json"))
    ap.add_argument("--out", default=str(DOC / "primitive-perf-chart.svg"))
    args = ap.parse_args()

    rep = json.loads(Path(args.report).read_text())
    rows = rep["rows"]

    # legend order key: keep original file order, group by (id, primitive,
    # size) preserving first-seen order.
    groups = []
    seen = {}
    for r in rows:
        key = (r["id"], r["primitive"], r["size"])
        if key not in seen:
            seen[key] = []
            groups.append((key, seen[key]))
        seen[key].append(r)

    # A group renders one row of bars per unique size bucket. Rows are
    # (id, primitive, size) unique per bucket already, so each group is one
    # bar row with 3 bars.
    gmax = max(
        max(r["cpython_gbs"], r.get("target_gbs") or 0) for r in rows
    )
    apy_vals = [r["antipythony_gbs"] for r in rows if r["antipythony_gbs"]]
    if apy_vals:
        gmax = max(gmax, max(apy_vals))
    gmax *= 1.15  # headroom for the value label

    y = 70
    parts = []
    parts.append('<?xml version="1.0" encoding="UTF-8"?>')
    total_h = y + len(groups) * (3 * (BAR_H + BAR_GAP) + GROUP_GAP) + 60
    parts.append(
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
        'viewBox="0 0 %d %d" font-family="Helvetica,Arial,sans-serif">'
        % (LABEL_W + CHART_W + 140, total_h, LABEL_W + CHART_W + 140, total_h))
    parts.append('<style>.v{font-size:11px;fill:#333}.t{font-size:12px}'
                 '.err{font-size:11px;fill:%s;font-weight:bold}</style>'
                 % ERR_COLOR)
    parts.append('<text x="10" y="26" font-size="17" font-weight="bold">'
                 'antipythony primitive throughput vs CPython 3.14 '
                 '(GB/s, log scale)</text>')
    src = esc(Path(args.report).name)
    parts.append('<text x="10" y="46" font-size="12" fill="#666">source: '
                 '%s (%s, %s) — generated by '
                 'tests/bench/primitive/gen_chart.py, numbers == JSON'
                 '</text>' % (src, esc(rep.get("machine", "?")),
                              esc(rep.get("generated", "?"))))

    # legend
    lx = 10
    for label, color in (("CPython 3.14", CPY_COLOR),
                         ("antipythony", APY_COLOR),
                         ("target", TGT_COLOR)):
        parts.append('<rect x="%d" y="54" width="14" height="12" '
                     'fill="%s"/>' % (lx, color))
        parts.append('<text x="%d" y="65" class="t">%s</text>'
                     % (lx + 18, label))
        lx += 30 + 8 * len(label)

    # hatch pattern def (used by ERROR placeholder bars)
    parts.append(
        '<defs><pattern id="hatch" width="8" height="8" '
        'patternTransform="rotate(45)" patternUnits="userSpaceOnUse">'
        '<line x1="0" y1="0" x2="0" y2="8" stroke="%s" stroke-width="3"/>'
        '</pattern></defs>' % ERR_COLOR)

    for (pid, prim, size), rs in groups:
        r = rs[0]  # one row per bucket
        y0 = y
        label = "%s %s [%s]" % (pid, prim, size)
        parts.append('<text x="10" y="%d" class="t" font-weight="bold">%s'
                     '</text>' % (y0 + BAR_H, esc(label)))
        verdict = r["verdict"]

        def bar(ybar, gbs, color, text, err=False):
            if err:
                parts.append(
                    '<rect x="%d" y="%d" width="%d" height="%d" '
                    'fill="none" stroke="%s" stroke-dasharray="4,3"/>'
                    % (BAR_X, ybar, CHART_W * 0.28, BAR_H, ERR_COLOR))
                parts.append(
                    '<rect x="%d" y="%d" width="%d" height="%d" '
                    'fill="url(%s)" opacity="0.35"/>'
                    % (BAR_X, ybar, CHART_W * 0.28, BAR_H, hatch_id))
                parts.append('<text x="%d" y="%d" class="err">%s</text>'
                             % (BAR_X + CHART_W * 0.28 + 8, ybar + BAR_H - 3,
                                text))
            else:
                ln = bar_len(gbs, gmax)
                parts.append('<rect x="%d" y="%d" width="%.1f" height="%d" '
                             'fill="%s"/>' % (BAR_X, ybar, ln, BAR_H, color))
                parts.append('<text x="%d" y="%d" class="v">%s</text>'
                             % (BAR_X + ln + 6, ybar + BAR_H - 3, text))

        # hatch is defined once in <defs> above; hatch_id names the pattern
        hatch_id = "hatch"
        cpy = r["cpython_gbs"]
        bar(y0, cpy, CPY_COLOR, fmt(cpy))
        y0 += BAR_H + BAR_GAP
        if r["antipythony_gbs"] is None:
            err_txt = "ERROR"
            msg = r.get("error", "")
            short = ("timeout" if "TIMEOUT" in msg
                     else msg.split("\n")[0][:60] if msg else "no measurement")
            bar(y0, 0, ERR_COLOR, err_txt + " — " + short, err=True)
        else:
            apy = r["antipythony_gbs"]
            bar(y0, apy, APY_COLOR, fmt(apy))
        y0 += BAR_H + BAR_GAP
        tgt = r.get("target_gbs")
        bar(y0, tgt, TGT_COLOR, fmt(tgt) +
            (" (%s)" % esc(r.get("target_source", "")) if tgt else ""))
        y0 += BAR_H + GROUP_GAP
        parts.append(
            '<text x="%d" y="%d" font-size="10" fill="%s">%s</text>'
            % (BAR_X + CHART_W + 60, y - 2,
               "#0a7d32" if verdict == "PASS" else
               (ERR_COLOR if verdict == "ERROR" else "#a05a00"),
               verdict))
        y = y0

    # axis ticks: decades
    parts.append('</svg>')
    Path(args.out).write_text("\n".join(parts))
    print("wrote %s (%d groups, gmax=%.1f GB/s)" % (args.out, len(groups), gmax))


def fmt(gbs):
    if gbs is None:
        return ""
    if gbs >= 100:
        return "%.0f" % gbs
    if gbs >= 10:
        return "%.1f" % gbs
    return "%.3g" % gbs


if __name__ == "__main__":
    main()
