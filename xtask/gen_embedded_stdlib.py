#!/usr/bin/env python3
# Leaf tier1-linecache (02.06 follow-up / 02.08 audit remaining-work row 4):
# generate the vendored_stdlib SOURCE store for ap-run's embedded importer
# fallback.
#
# Output: crates/ap-run/src/embedded_stdlib/data.rs — one `include_bytes!`
# arm per vendored .py file, keyed by the IMPORT PATH the importer resolves
# (path relative to vendored_stdlib/, .py + __init__ folded away, '/' → '.'),
# byte-order sorted (Rust str Ord — binary_search ready). Deterministic.
#
# Excluded from the store (pure CPython extras the runtime's chains never
# import; keeps the AoT binary delta honest — docs/aot-stdlib-embed.md):
# pydoc_data/, _pyrepl/.
#
# SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "vendored_stdlib")
OUT = os.path.join(ROOT, "crates/ap-run/src/embedded_stdlib/data.rs")
EXCLUDE_DIRS = {"pydoc_data", "_pyrepl"}

rows = []
total = 0
for dirpath, dirnames, filenames in os.walk(SRC):
    dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
    for fn in filenames:
        if not fn.endswith(".py"):
            continue
        full = os.path.join(dirpath, fn)
        rel = os.path.relpath(full, SRC)
        key = rel[: -len(".py")].replace(os.sep, "/")
        if key.endswith("/__init__"):
            key = key[: -len("/__init__")]
        key = key.replace("/", ".")
        size = os.path.getsize(full)
        total += size
        rows.append((key, rel, size))

# Package face wins over a sibling same-named module face (CPython
# FileFinder checks the directory first). Deterministic: sort the faces
# by rel path, keep the FIRST (a package __init__ sorts before a sibling
# .py under the same name since "__init__" < "<name>.py" is not relied on
# — we explicitly prefer the __init__ face).
by_key: dict[str, tuple[str, str, int]] = {}
for key, rel, size in rows:
    is_init = rel.endswith("__init__.py")
    prev = by_key.get(key)
    if prev is None:
        by_key[key] = (key, rel, size)
    elif is_init and not prev[1].endswith("__init__.py"):
        by_key[key] = (key, rel, size)
rows = list(by_key.values())

# Rust str Ord == byte order: sort by the KEY's UTF-8 bytes.
rows.sort(key=lambda r: r[0].encode())

with open(OUT, "w") as f:
    f.write("// @generated by xtask/gen_embedded_stdlib.py — DO NOT EDIT.\n")
    f.write("//\n")
    f.write("// The vendored_stdlib source store for the importer's embedded fallback\n")
    f.write("// (leaf tier1-linecache): a stdlib binary ships WITHOUT the build\n")
    f.write("// machine's vendored_stdlib/ directory, so linecache/traceback/import\n")
    f.write("// resolve vendored pure-Python sources from this static table.\n")
    f.write("// Regenerate with xtask/gen_embedded_stdlib.py (deterministic: the\n")
    f.write("// same tree emits the same file; keys are byte-order sorted).\n")
    f.write("//\n")
    f.write("// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n\n")
    f.write("/// (import path, bytes) pairs — byte-order sorted by path, generated.\n")
    f.write("pub static EMBEDDED_STDLIB_SOURCES: &[(&str, &[u8])] = &[\n")
    for key, rel, _ in rows:
        f.write(
            f'    ("{key}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), '
            f'"/../../vendored_stdlib/{rel}"))),\n'
        )
    f.write("];\n\n")
    f.write("/// Store stats (mirrored in docs/aot-stdlib-embed.md).\n")
    f.write(f"pub const EMBEDDED_STDLIB_FILE_COUNT: usize = {len(rows)};\n")

print(f"generated {OUT}: {len(rows)} files, {total} source bytes")
